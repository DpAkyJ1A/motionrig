/** `n` with the form of `key` (`one|few|many` forms, `|`-separated) its locale's plural rules pick. */
export function count(n: number, key: Key): string {
  const forms = t(key).split('|');
  const rule = new Intl.PluralRules(getConfig().locale).select(n);
  return `${n} ${forms[rule === 'one' ? 0 : rule === 'few' ? 1 : forms.length - 1] ?? forms[0]}`;
}

/** A panel string: `config.messages` wins over the `config.locale` table. */
export function t(key: Key): string {
  const { locale, messages } = getConfig();
  return messages?.[key] ?? (locale === 'ru' ? ru : en)[key];
}
